"""
逻辑回归模型介绍：
    概述：
        属于有监督学习，即有特征，有标签，且标签是离散的
        主要适用于二分类问题
    原理：
        把线性回归处理后的预测值 --> 通过Sigmoid激活函数，映射到[0,1] 概率  --> 基于自定义的阈值，结合概率来分类
    损失函数：
        极大似然估计函数的负数形式

    混淆矩阵：
        True：真      False：假         Positive：正例         Negative：反例

                        预测值（正例）                 预测值（反例）
        真实值（正例）      真正例（TP）                  伪反例（FN）
        真实值（反例）      伪正例（FP）                  真反例（TN）

        真正例（TP）：预测为正例，实际也为正例
        假反例（FN）：预测为反例，实际为正例
        假正例（FP）：预测为正例，实际为反例
        真反例（TN）：预测为反例，实际也为反例

        精确率（Precision）：TP/(TP+FP)
        召回率（Recall）：TP/(TP+FN)
        F1分数（F1 Score）：2*Precision*Recall/(Precision+Recall)
"""