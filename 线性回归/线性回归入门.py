"""
线性回归介绍（Linear Regressor）：
    概述/目的：
        用线性公式来描述多个变量（特征）和一个因变量（标签）之间的关系，对其关系进行建模，基于特征预测标签
        线性回归属于：有监督学习，即有特征，有标签，且标签是连续的

    分类：
        一元线性回归：一个特征，一个标签
        多元线性回归：多个特征，一个标签
    公式：
        一元线性回归：
            y = kx + b --> y = wx + b
                k: 数学中叫斜率，机器学习中叫 weight(权重)，简称w
                b: 数学中叫截距，机器学习中叫 bias(偏置)，简称b
        多元线性回归：
            y = w1x1 + w2x2 + ... + wnxn + b
              = w的转置 * x + b

    误差：
        误差 = 预测值 - 真实值

    损失函数（Loss Function）：
        衡量每个样本的预测值和真实值效果的函数，让损失函数最小，就是让误差和小，线性回归效率，评估就越高

    损失函数最小的方法：
        1.正规方程法
            通过求导，让导数等于0，从而求解w和b

            弊端：
                计算量大，只适用于特征数少的情况

        2.梯度下降法
            通过迭代，让损失函数不断减小

            公式：
                Θ₂ = Θ₁ - α * ∇Θ₁
                Θ₂: 第二次迭代的参数
                Θ₁: 第一次迭代的参数
                α: 学习率（一般在0.001~0.01之间）
                ∇Θ₁: 损失函数对参数Θ₁的偏导数

            分类：
                1.全梯度下降法FGD（Full Gradient Descent）
                    通过计算所有样本点的梯度，来更新参数
                2.随机梯度下降法SGD
                    通过计算随机一个样本点的梯度，来更新参数
                3.小批量梯度下降法mini-batch
                    通过计算随机选择小批量样本点的梯度，来更新参数
                4.随机平均梯度下降法SAG
                    通过计算随机一个样本和以往样本的均值，来更新参数

    常见的损失函数：
        1.最小二乘：
            每个样本点误差的平方和

        2.均方误差（Mean Squared Error, MSE）
            MSE = （每个样本点）误差的平方和 / 样本总数

        3.平均绝对误差（Mean Absolute Error, MAE）
            MAE = （每个样本点）误差的绝对值之和 / 样本总数

        4.均方根误差（Root Mean Squared Error, RMSE）
            RMSE = 均方误差的平方根

        一般使用MAE和RMSE
        RMSE比MAE更能反映出真实误差

        多元线性回归的损失函数公式：
            J（w）= (1/2m) ∑（w₀ + w₁x₁ + w₂x₂ + ... + wnxn - y_true）²         采用均方误差
                m: 样本总数
                w₀：偏置b
                前面加2是因为平方后求导会变2，为了方便计算，直接乘以2
    矩阵相关：
        1范数 = 矩阵中所有元素绝对值之和，即曼哈顿距离
        2范数 = 矩阵中所有元素平方和的平方根，即欧式距离
"""


#正规方程法
#导包
from sklearn.linear_model import LinearRegression

#线性回归API入门
#1.准备数据
x_train = [[160],[165],[172],[175],[181]]
y_train = [52.4,55.2,62,66,70.5]
x_test = [[176]]

#2.模型训练
estimator = LinearRegression()
estimator.fit(x_train, y_train)
#因为是线性回归，我们可以查看下权重和偏置
print("权重：", estimator.coef_)
print("偏置：", estimator.intercept_)

#3.模型预测
y_pred = estimator.predict(x_test)
print("预测值：", y_pred)
