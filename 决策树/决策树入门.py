"""
熵：数据的混乱程度，熵越小，数据越有序，熵越大，数据越混乱。
    公式：
    例：特征α=[a,a,b,a,b,a], 特征β=[1,2,3,4,5,6],目标值=[A,A,B,A,B,B]
    熵 = -标签列A分类占比 * log₂(标签列A分类占比) - 标签列B分类占比 * log₂(标签列B分类占比)
      = -3/6 * log₂(3/6) - 3/6 * log₂(3/6) = 1

条件熵：
    特征α的条件熵 = 特征x占比 * (-特征列α中标签列A分类占比 * log₂(标签列A分类占比) - 标签列B分类占比 * log₂(标签列B分类占比))
      = 4/6 * (-3/4 * log₂(3/4) - 1/4 * log₂(1/4)) + 2/6 * (-2/2 * log₂(2/2)) = 0.54
    特征β的条件熵 = -特征列β中标签列A分类占比 * log₂(标签列A分类占比) - 标签列B分类占比 * log₂(标签列B分类占比)
      =  1/6 * (-1/6 * log₂(1/1)) * 6 = 0

信息增益：
    信息增益越大，该特征越适合做父节点
    信息增益 = 熵 - 条件熵
      特征α的信息增益 = 1 - 0.54 = 0.46
      特征β的信息增益 = 1 - 0 = 1

特征熵：
    特征熵 = -特征列A分类占比 * log₂(标签列A分类占比) - 标签列B分类占比 * log₂(标签列B分类占比)
    特征α的特征熵 = -4/6 * log₂(4/6) - 2/6 * log₂(2/6) = 0.92
    特征β的特征熵 = -1/6 * log₂(1/6) * 6 = 2.59

信息增益率:
    信息增益率 = 信息增益 / 特征熵
    特征α的信息增益率 = 0.46 / 0.92 = 0.5
    特征β的信息增益率 = 1 / 2.59 = 0.39

基尼值:
    基尼值 = 1 - (各分类概率和)²

基尼指数：
    基尼指数 = 各分类占比 * 当前分类的基尼值

    例：特征a = [A,A,A,A,B,B],目标值 = [y,n,y,y,y,n]
    A基尼值 = 1 - (3/4)² - (1/4)² = 0.375
    B基尼值 = 1 - (1/2)² - (1/2)² = 0.5
    基尼指数 = 4/6 * 0.375 + 2/6 * 0.5 = 0.42


ID3决策树
    基于信息增益，选择信息增益最大的特征作为决策节点
    特点：
        ID3只能对离散属性的数据集构成决策树
        倾向于选择取值较多的属性

C4.5决策树
    基于信息增益率，选择信息增益率最大的特征作为决策节点
    特点：
        缓解了ID3倾向于选择取值较多的属性的问题
        可处理连续数值型属性，也增加了对缺失值的处理方法
        只适用于能够驻留于内存的数据集，大数据集无能为力

CART决策树
    基于gini指数，选择gini指数最小的特征作为决策节点
    特点：
        可以进行分类和回归，可处理离散属性，也处理连续属性
        采用基尼指数，计算量减小
        一定是二叉树
"""